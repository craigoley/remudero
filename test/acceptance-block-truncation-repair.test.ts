// test/acceptance-block-truncation-repair.test.ts — W1-T2316: the retro rung ships bodies its own
// gates reject, because `bodyNeedsAcceptanceRepair` could not express truncation.
//
// WHAT IS REAL HERE. `bodyNeedsAcceptanceRepair`, `ensureJudgeableBody` and `renderAcceptanceBlock`
// are the production functions from `src/lib/plan-pr-emitter.ts`; `parseAcceptanceBlock` and
// `acceptanceBlockDiagnostics` are the production readers from `src/lib/review.ts`. Nothing is
// re-implemented and no reader is stubbed — a stubbed parser would make every assertion here
// vacuous, since the whole defect is a disagreement between two real readers over the same text.
//
// THE FIXTURE IS r29's OWN TEXT (#2908), RE-BROKEN. Its body as STORED ON GITHUB TODAY is healthy —
// written 5, parsed 5, emptyProofs 0 — because it was hand-repaired between its 03:41Z creation and
// its 12:23Z merge, carrying no `superseded` marker. So the `written 5 / parsed 1` reading the shard
// records describes a body that no longer exists, and a fixture claiming to be "r29's stored body"
// would be false. What is used instead is r29's five real bullets with ONE wrap reintroduced, which
// is the transformation the incident describes, and the numbers it reproduces are the incident's.
import assert from "node:assert/strict";
import { test } from "node:test";
import { acceptanceBlockDiagnostics, parseAcceptanceBlock } from "../src/lib/review.js";
import {
  bodyNeedsAcceptanceRepair,
  ensureJudgeableBody,
  renderAcceptanceBlock,
  SUPERSEDED_HEADER_SUFFIX,
} from "../src/lib/plan-pr-emitter.js";

/** THE PREDICATE AS IT STOOD BEFORE W1-T2316, kept here so every "newly caught" claim below is
 *  measured against the old behaviour rather than asserted about it. Copied from the function this
 *  task widened, not imported — the point is to compare two definitions. */
function oldPredicate(body: string): boolean {
  const parsed = parseAcceptanceBlock(body);
  if (parsed.length === 0) return true;
  return parsed.some((c) => c.proof.trim().length === 0);
}

const R29_BULLETS = [
  "- SHIPPED log entry added for what landed this cycle, each with its PR link | grep: RETRO-1787714349337 (2026-08-26) in MASTER-PLAN.md",
  "- NET STATE refreshed to reflect reality | grep: THIS CYCLE (RETRO-1787714349337 in MASTER-PLAN.md",
  "- Calibration table present, exactly as the gather produced it | grep: implement | 47 | 14 | in MASTER-PLAN.md",
  "- Failures mined into PROPOSALS ONLY, never filed | grep: rule 15, never auto-filed in MASTER-PLAN.md",
  "- COMPRESSION done, net-negative, deletions named | grep: net-negative in MASTER-PLAN.md",
];
const r29Body = (bullets: string[]): string =>
  ["r29 retro sync.", "", "## Acceptance", "", ...bullets, "", "Generated by a worker."].join("\n");

/** r29's shape: the wrap lands AFTER the `|`, so the first criterion keeps a NON-EMPTY proof and
 *  every later bullet is discarded. This is the variant the old predicate cannot see. */
const WRAPPED_AFTER_PIPE = r29Body([
  "- SHIPPED log entry added for what landed this cycle, each with its PR link | grep: RETRO-1787714349337",
  "  (2026-08-26) in MASTER-PLAN.md",
  ...R29_BULLETS.slice(1),
]);
/** The other wrap: BEFORE the `|`, which leaves an empty proof and was already caught. */
const WRAPPED_BEFORE_PIPE = r29Body([
  "- SHIPPED log entry added for",
  "  what landed this cycle, each with its PR link | grep: RETRO-1787714349337 (2026-08-26) in MASTER-PLAN.md",
  ...R29_BULLETS.slice(1),
]);
const HEALTHY = r29Body(R29_BULLETS);

const DIALECT_FALLBACK = [
  { claim: "the retro's plan-only sync PR is gate-compliant", proof: "grep: SHIPPED in MASTER-PLAN.md" },
  { claim: "the calibration table is present", proof: "unit test: retro calibration table" },
];

// ── criterion 1: more bullets than parsed criteria ⇒ needs repair ────────────────────────────

test("W1-T2316: a body writing more bullets than it parses is recognised as needing repair, and the old predicate did not see it", () => {
  const d = acceptanceBlockDiagnostics(WRAPPED_AFTER_PIPE);
  assert.equal(d.bulletsWritten, 5, "r29's five bullets are still counted as written");
  assert.equal(d.criteriaParsed, 1, "the parser reaches only the first");
  assert.equal(d.emptyProofs, 0, "and that first criterion carries a NON-empty proof — why it read healthy");
  assert.equal(oldPredicate(WRAPPED_AFTER_PIPE), false, "FALSIFIER: the pre-W1-T2316 predicate is silent on this body");
  assert.equal(bodyNeedsAcceptanceRepair(WRAPPED_AFTER_PIPE), true, "the widened predicate fires");
});

// ── criterion 2: a reported truncation ⇒ needs repair ────────────────────────────────────────

test("W1-T2316: a body reporting a truncated bullet is recognised as needing repair, and truncatedAtBullet is the same fact in 1-based clothing", () => {
  const d = acceptanceBlockDiagnostics(WRAPPED_AFTER_PIPE);
  assert.equal(d.truncatedAtBullet, 2, "the parser stopped before bullet 2");
  assert.equal(bodyNeedsAcceptanceRepair(WRAPPED_AFTER_PIPE), true);
  // NOT two conditions: truncatedAtBullet is defined as parsed < written ? parsed + 1 : undefined,
  // so testing it separately would test one inequality twice. Pinned so a future reader can see it.
  for (const body of [WRAPPED_AFTER_PIPE, WRAPPED_BEFORE_PIPE, HEALTHY, "no header at all"]) {
    const x = acceptanceBlockDiagnostics(body);
    assert.equal(
      x.truncatedAtBullet !== undefined,
      x.criteriaParsed < x.bulletsWritten,
      "truncatedAtBullet is exactly `parsed < written`",
    );
  }
});

// ── criterion 3: a healthy block is untouched ────────────────────────────────────────────────

test("W1-T2316: a body whose bullets all parse is left untouched — the widened predicate does not repair healthy bodies", () => {
  const d = acceptanceBlockDiagnostics(HEALTHY);
  assert.equal(d.bulletsWritten, 5);
  assert.equal(d.criteriaParsed, 5, "written and parsed agree");
  assert.equal(bodyNeedsAcceptanceRepair(HEALTHY), false);
  assert.equal(ensureJudgeableBody(HEALTHY, DIALECT_FALLBACK), HEALTHY, "returned byte-identical");
  // The emitter's own output must also stay healthy under the widened predicate.
  const emitted = `Acceptance:\n${renderAcceptanceBlock(DIALECT_FALLBACK).split("\n").slice(1).join("\n")}`;
  assert.equal(bodyNeedsAcceptanceRepair(emitted), false, "renderAcceptanceBlock round-trips under the widened rule");
});

// ── criterion 4: the original triggers are unchanged ─────────────────────────────────────────

test("W1-T2316: the zero-criteria and empty-proof triggers still fire exactly as before, on every shape the old predicate decided", () => {
  const cases: Array<[string, boolean]> = [
    ["", true],
    ["just prose, no header", true],
    ["## Acceptance\n\n- a claim with no proof separator", true],
    [WRAPPED_BEFORE_PIPE, true],
    [HEALTHY, false],
  ];
  for (const [body, expected] of cases) {
    assert.equal(oldPredicate(body), expected, `old predicate unchanged for: ${JSON.stringify(body.slice(0, 40))}`);
    assert.equal(bodyNeedsAcceptanceRepair(body), expected, `widened predicate agrees for: ${JSON.stringify(body.slice(0, 40))}`);
  }
  // STRICT SUPERSET, both directions: nothing the old predicate flagged loses its flag.
  for (const body of [WRAPPED_AFTER_PIPE, WRAPPED_BEFORE_PIPE, HEALTHY, "", "no header"]) {
    if (oldPredicate(body)) assert.equal(bodyNeedsAcceptanceRepair(body), true, "a flag is never lost");
  }
});

// ── criterion 5: a repaired body parses everything it writes, with dialect-prefixed proofs ────

test("W1-T2316: a repaired body parses every claim it writes and each proof carries a dialect prefix", () => {
  const repaired = ensureJudgeableBody(WRAPPED_AFTER_PIPE, DIALECT_FALLBACK);
  const d = acceptanceBlockDiagnostics(repaired);
  assert.equal(d.bulletsWritten, d.criteriaParsed, "written === parsed in the repaired body");
  assert.equal(d.criteriaParsed, DIALECT_FALLBACK.length);
  assert.equal(d.emptyProofs, 0);
  assert.equal(d.defective, false, "the diagnostics reader calls the repaired body healthy");
  for (const c of parseAcceptanceBlock(repaired)) {
    assert.match(c.proof, /^(unit test|grep):\s/, `every repaired proof carries a dialect prefix: ${c.proof}`);
  }
  assert.ok(repaired.includes(SUPERSEDED_HEADER_SUFFIX), "the defective header is demoted, so the truncation is DECLARED rather than silent");
  assert.ok(repaired.includes(R29_BULLETS[1]!), "the author's original bullets stay in the body as readable prose");
  // THE REPAIR DOES NOT REFLOW, which is why it cannot make a capped verdict worse: it appends the
  // caller's criteria rather than resurrecting the author's five prose-proof bullets.
  assert.equal(parseAcceptanceBlock(repaired).length, DIALECT_FALLBACK.length, "judged criteria are the caller's, not the author's five");
});

test("W1-T2316: ensureJudgeableBody refuses to CLAIM a repair it did not complete", () => {
  assert.throws(
    () => ensureJudgeableBody(WRAPPED_AFTER_PIPE, [{ claim: "a claim that\ncarries a newline", proof: "grep: x in y" }]),
    /still needs repair/,
    "a fallback that cannot round-trip surfaces as a caller bug rather than a false `repaired` log",
  );
});

// ── criterion 6: never inspects free prose outside an acceptance block ───────────────────────

test("W1-T2316: the predicate never inspects free prose outside an acceptance block — freely-wrapped plan prose is silent", () => {
  // Real plan-shard prose, wrapped the way every rationale in plan/tasks.d/ is wrapped. If the
  // widened arm could read this, a filing would be flagged for its typography.
  const prose = [
    "(2) BOTH CONSUMERS ARE LINE-SCOPED, AND THAT IS THE COMMON CAUSE.",
    "`parseAcceptanceBlock` (`src/lib/review.ts`) ends the block at any indented line that is not a",
    "fresh `proof:`, so a claim wrapped onto a second line truncates every bullet after it.",
    "  - a bullet, wrapped",
    "    onto a second line, inside ordinary prose",
    "  - and another one",
    "",
    "MASTER-PLAN paragraphs re-wrap constantly and no gate reads them for bullet arithmetic.",
  ].join("\n");
  const d = acceptanceBlockDiagnostics(prose);
  assert.equal(d.headerFound, false, "no Acceptance header, so nothing is counted");
  assert.equal(d.bulletsWritten, 0, "bullets outside a block are not counted, however they wrap");
  // The zero-criteria arm decides this body, exactly as it did before W1-T2316.
  assert.equal(oldPredicate(prose), true);
  assert.equal(bodyNeedsAcceptanceRepair(prose), true, "same verdict, same reason — not the truncation arm");
  // And the truncation arm on its own is silent here, which is the property under test.
  assert.equal(d.headerFound && d.bulletsWritten > d.criteriaParsed, false, "the widened arm cannot fire without a header");
});

// ── criterion 7: nothing relaxes what counts as judgeable ────────────────────────────────────

test("W1-T2316: nothing in the widened path relaxes what counts as judgeable", () => {
  // The parser's end-of-block rule is untouched: the truncated body still resolves ONE criterion.
  assert.equal(parseAcceptanceBlock(WRAPPED_AFTER_PIPE).length, 1, "parseAcceptanceBlock is unchanged");
  // And repairing does NOT make the four hidden criteria judgeable — it declares the defect and
  // substitutes the caller's block. A remedy that resurrected them would be guessing at intent.
  const repaired = ensureJudgeableBody(WRAPPED_AFTER_PIPE, DIALECT_FALLBACK);
  const claims = parseAcceptanceBlock(repaired).map((c) => c.claim);
  for (const hidden of R29_BULLETS.slice(1)) {
    const text = hidden.slice(2).split(" | ")[0]!;
    assert.ok(!claims.includes(text), `a truncated criterion is never promoted to judgeable: ${text.slice(0, 40)}`);
  }
  // The widening only ever moves a body from "healthy" to "needs repair", never the reverse.
  for (const body of [WRAPPED_AFTER_PIPE, WRAPPED_BEFORE_PIPE, HEALTHY, "", "no header"]) {
    assert.ok(bodyNeedsAcceptanceRepair(body) || !oldPredicate(body), "never returns false where the old predicate returned true");
  }
});
