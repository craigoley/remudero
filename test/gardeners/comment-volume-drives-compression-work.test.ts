const signal = await import(pathToFileURL(join(REPO_ROOT, "scripts/comment-load-ratchet.mjs")).href);
const census = await import(pathToFileURL(join(REPO_ROOT, "scripts/census-precheck.mjs")).href);
const comments = (n: number) => "// operative comment\n".repeat(n) + "export const unchanged = 1;\n";

test("comment volume signals debt without blocking the command, push census or merged-tree judgement", t => {
  const repo = gitRepo({ scope: t });
  mkdirSync(join(repo.dir, "src"));
  mkdirSync(join(repo.dir, "scripts"));
  writeFileSync(join(repo.dir, "src/subject.ts"), comments(1));
  writeFileSync(join(repo.dir, "scripts/comment-load-baseline.json"), "not a required signal input\n");
  repo.git("add", "."); repo.git("commit", "-qm", "base");
  const base = repo.git("rev-parse", "HEAD");
  writeFileSync(join(repo.dir, "src/subject.ts"), comments(900));
  repo.git("add", "."); repo.git("commit", "-qm", "document the invariant");
  assert.equal(typeof signal.measureCommentLoadSignal, "function", "comment volume has a nonblocking measurement path");
  const report = signal.measureCommentLoadSignal(repo.dir, base);
  assert.equal(report.schema_version, 2);
  assert.equal(report.head, repo.git("rev-parse", "HEAD"));
  assert.equal(report.hotspots[0].comments, 900);
  assert.equal(report.hotspots[0].followup, true);
  assert.ok(report.oversized_added_blocks.length > 0);
  t.mock.method(console, "log", () => {});
  assert.equal(signal.main(["--root", repo.dir, "--base", base, "--strict"]), 0);
  for (const command of ["comment-load-signal", "comment-load-ratchet"]) {
    const actual = spawnSync("npm", ["run", "--silent", command, "--", "--root", repo.dir, "--base", base], { cwd: REPO_ROOT, encoding: "utf8" });
    assert.equal(actual.status, 0, actual.stdout + actual.stderr);
    assert.match(actual.stdout, /nonblocking-followup/);
  }
  assert.equal(readFileSync(join(repo.dir, "scripts/comment-load-baseline.json"), "utf8"), "not a required signal input\n");
  assert.equal(signal.main(["--root", repo.dir, "--base", "missing-ref"]), 2);
  const read = (p: string) => p === "src/subject.ts" ? comments(900) : p === "scripts/comment-load-baseline.json" ? '{"src/subject.ts":1}' : null;
  const input = { changed: ["src/subject.ts"], measuredFiles: ["src/subject.ts"], testFiles: [], srcFiles: [], readHead: read, readBase: (p: string) => p === "src/subject.ts" ? comments(1) : read(p) };
  assert.deepEqual(census.evaluateCensusPrecheck(input), []);
  const judgement = judgeMergedRatchets({ mainSha: base, headSha: repo.git("rev-parse", "HEAD"), changed: ["src/subject.ts"], measuredFiles: ["src/subject.ts"],
    readMerged: read, readMain: p => p === "src/subject.ts" ? comments(1) : read(p) });
  assert.equal(judgement.verdict, "clean");
  assert.ok(judgement.uncounted.some(row => row.gate === "comment-load" && row.class === "advisory"));
});

test("the gate gardener files one priority-one compression task through normal admission and deduplicates it", async t => {
  assert.equal(typeof commentCompressionCandidates, "function", "the registered gardener produces compression follow-ups");
  const { commentCompressionOrigin, nextCommentCompression } = await import("#src/lib/comment-compression.js");
  const repo = gitRepo({ scope: t });
  mkdirSync(join(repo.dir, "src")); mkdirSync(join(repo.dir, "plan"));
  writeFileSync(join(repo.dir, "plan/tasks.yaml"), "[]\n");
  writeFileSync(join(repo.dir, "src/subject.ts"), comments(900));
  writeFileSync(join(repo.dir, "src/second.ts"), comments(500));
  repo.git("add", "."); repo.git("commit", "-qm", "measured subjects");
  const probes = await loadGateProbes(REPO_ROOT);
  const events: Array<{ step: string; extra?: Record<string, unknown> }> = [];
  const deps = { repoRoot: repo.dir, stateDir: join(repo.dir, "state"), log: (step: string, extra?: Record<string, unknown>) => { events.push({ step, extra }); }, openWorkspace: () => { throw new Error("unused workspace port"); } } satisfies GardenerDeps;
  const sources = { openOrigins: () => [], mintTaskId: () => "W1-T999901" };
  const actions = commentCompressionCandidates(deps, probes, sources);
  assert.equal(actions.length, 1);
  assert.equal(actions[0].file, "src/subject.ts");
  assert.equal(commentCompressionCandidates(deps, probes, { ...sources, openOrigins: () => [actions[0].target] })[0].file, "src/second.ts");
  assert.equal(nextCommentCompression([{ file: "src/subject.ts", comments: 900 }], new Set([commentCompressionOrigin("src/subject.ts")])), undefined);
  const rendered = renderCommentCompressionShard({ file: "src/subject.ts", comments: 900 }, "W1-T999901");
  assert.equal(rendered.refused, undefined);
  const task = parse(rendered.text)[0];
  assert.equal(task.priority, 1);
  assert.equal(task.verify, "human");
  assert.equal(task.author_class, "machine");
  assert.equal(machineShardFilingRefusal(rendered.text, "proposed.yaml", { pathExists: p => p === "src/subject.ts" }), undefined);
  assert.match(machineShardFilingRefusal(rendered.text.replace("verify: human", "verify: auto"), "proposed.yaml", { pathExists: p => p === "src/subject.ts" }) ?? "", /machine-author-verify/);
  assert.match(machineShardFilingRefusal(rendered.text.replace("    - src/subject.ts", "    - src/other.ts"), "proposed.yaml", { pathExists: () => true }) ?? "", /machine-filing-admission/);
  mkdirSync(join(repo.dir, ".github/workflows"), { recursive: true });
  mkdirSync(join(repo.dir, "scripts"), { recursive: true });
  mkdirSync(join(repo.dir, "learnings"), { recursive: true });
  writeFileSync(join(repo.dir, ".github/workflows/ci-gate.yml"), "jobs:\n  ci-gate:\n    env:\n      REQUIRED: '[]'\n      ADVISORY: '[]'\n");
  writeFileSync(join(repo.dir, "scripts/source-size-baseline.json"), "{}\n");
  writeFileSync(join(repo.dir, "scripts/learnings-budget-baseline.json"), '{"measuredChars":0,"measuredActiveEntries":0,"capChars":42000}\n');
  repo.git("add", "."); repo.git("commit", "-qm", "garden measurement inputs");
  const spec = gateGardenSpec(deps, probes, sources);
  assert.ok(spec.inventory().candidates.some(action => action.class === "compress" && action.target === actions[0].target), "the actual registered inventory reaches the follow-up producer");
  const workspace = { root: repo.dir, branch: "run-unfiled-1792897200000", land: () => "https://github.com/fixture/comments/pull/5" } as unknown as GardenCheckout;
  const plan = { acting: ["compress" as const], actions };
  const ids = await spec.prepare!(workspace, plan, true);
  const result = spec.apply(workspace, plan, {}, ids)!;
  assert.equal(result.paths.length, 1);
  const filed = readFileSync(join(repo.dir, result.paths[0]), "utf8");
  assert.equal(parse(filed)[0].priority, 1);
  assert.equal(events.some(event => event.step === "gate_garden.comment_compression_filed"), false);
  assert.equal(workspace.land(result), "https://github.com/fixture/comments/pull/5");
  assert.deepEqual(events.find(event => event.step === "gate_garden.comment_compression_filed")?.extra,
    { file: "src/subject.ts", observed_comments: 900, priority: 1, origin: actions[0].target });
  assert.equal(commentCompressionCandidates(deps, probes, sources)[0].file, "src/second.ts");
  const refused = gateGardenSpec(deps, probes, { ...sources, admissionViolations: () => ["fixture refusal"] });
  assert.throws(() => refused.apply(workspace, plan, {}), /fixture refusal/);
  repo.addRemote("origin", "https://github.com/fixture/comments.git");
  const shim = ghShim([{ when: "pulls?state=open", stdout: JSON.stringify([[{ body: "comment-compression:src/second.ts" }]]), delaySeconds: 0.1 }]);
  const priorPath = process.env.PATH;
  const priorCache = process.env.RMD_GH_CACHE_HOME;
  t.after(() => { process.env.PATH = priorPath; if (priorCache === undefined) delete process.env.RMD_GH_CACHE_HOME; else process.env.RMD_GH_CACHE_HOME = priorCache; rmSync(shim.dir, { recursive: true, force: true }); });
  process.env.PATH = `${shim.dir}:${priorPath}`;
  process.env.RMD_GH_CACHE_HOME = join(repo.dir, "isolated-read-cache");
  const real = gateGardenSpec(deps, probes, { mintTaskId: sources.mintTaskId });
  assert.throws(() => real.inventory(), /requires an awaited open-PR inventory/);
  let settled = false;
  const pending = real.inventoryAsync!();
  void pending.then(() => { settled = true; });
  await new Promise<void>(resolve => setImmediate(resolve));
  assert.equal(settled, false, "the real default read yields while its child is in flight");
  assert.equal((await pending).candidates.filter(action => action.class === "compress").length, 0);
  assert.match(shim.calls()[0], /api --paginate --slurp repos\/fixture\/comments\/pulls/);
  shim.addRoute({ when: "pulls?state=open", stdout: "[null]" });
  await assert.rejects(real.inventoryAsync!(), /page corpus is unreadable/);
  shim.addRoute({ when: "pulls?state=open", stdout: JSON.stringify([[{}]]) });
  await assert.rejects(real.inventoryAsync!(), /body is unreadable/);
  shim.addRoute({ when: "pulls?state=open", stderr: "cannot read follow-ups", exit: 7 });
  await assert.rejects(real.inventoryAsync!(), /cannot read follow-ups/);
  repo.git("remote", "set-url", "origin", "not-a-repository");
  await assert.rejects(real.inventoryAsync!(), /origin does not identify a GitHub repository/);
  const callsBeforeOff = shim.calls().length;
  mkdirSync(deps.stateDir, { recursive: true });
  writeFileSync(join(deps.stateDir, "GATE_OFF-compress"), "");
  writeFileSync(join(deps.stateDir, "GATE_OFF-defuse"), "");
  assert.equal((await real.inventoryAsync!()).candidates.filter(action => action.class === "compress").length, 0);
  assert.equal(shim.calls().length, callsBeforeOff, "disabled follow-up work makes no new forge read");
  const monolith = join(repo.dir, "plan/tasks.yaml");
  rmSync(monolith);
  assert.throws(() => commentCompressionCandidates(deps, probes, sources), /plan context is unreadable/);
  writeFileSync(monolith, "[]\n");
  const shardDir = join(repo.dir, "plan/tasks.d");
  writeFileSync(join(shardDir, "broken.yaml"), "- id: [unfinished\n");
  assert.throws(() => commentCompressionCandidates(deps, probes, sources));
  rmSync(join(shardDir, "broken.yaml"));
  renameSync(shardDir, join(repo.dir, "held-shards"));
  writeFileSync(shardDir, "not a shard directory\n");
  assert.throws(() => commentCompressionCandidates(deps, probes, sources), /ENOTDIR/);
  rmSync(shardDir);
  renameSync(join(repo.dir, "held-shards"), shardDir);



});
