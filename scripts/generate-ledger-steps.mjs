// scripts/generate-ledger-steps.mjs
//
// docs/ledger-steps.md generator + drift gate (W1-T2764).
//
// The registry (src/lib/ledger-steps.ts's LEDGER_STEPS) is the one source of truth for what a
// registered ledger step means, who writes it and what that writer can return. This script renders
// a human-browsable page from EXACTLY that registry -- same discipline as
// scripts/generate-cli-reference.mjs rendering docs/cli-reference.md from src/run-task.ts's
// COMMANDS -- so the committed page cannot drift from the registry `meaningOfStep` reads.
//
// Usage:
//   npm run ledger-steps          # regenerate docs/ledger-steps.md
//   npm run ledger-steps:check    # exit 1 if the committed file is stale
//
// Run under `node --import tsx` (not plain `node`): LEDGER_STEPS lives in a .ts module, and only
// tsx's loader can import that from a plain .mjs script outside tsconfig's build.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { pathToFileURL } from "node:url";
import { LEDGER_STEPS } from "../src/lib/ledger-steps.ts";

const DEFAULT_OUT = join("docs", "ledger-steps.md");

/** Render the full page from `rows` -- pure function of the registry, no I/O. Grouped by
 *  `family`, families and rows both in `step`-sorted order so two regenerations are byte-
 *  identical (the same "content-only, no timestamp" discipline generate-cli-reference.mjs uses,
 *  which is what makes `--check` a meaningful staleness gate rather than a permanent false
 *  positive). */
export function renderLedgerStepsPage(rows) {
  const byFamily = new Map();
  for (const row of [...rows].sort((a, b) => a.step.localeCompare(b.step))) {
    if (!byFamily.has(row.family)) byFamily.set(row.family, []);
    byFamily.get(row.family).push(row);
  }
  const families = [...byFamily.keys()].sort();

  const lines = [];
  lines.push("<!--");
  lines.push("AUTO-GENERATED -- DO NOT EDIT BY HAND.");
  lines.push("Generated by scripts/generate-ledger-steps.mjs from the LEDGER_STEPS registry in");
  lines.push("src/lib/ledger-steps.ts -- the SAME source `meaningOfStep` (read by `rmd ledger-grep`)");
  lines.push("resolves against (W1-T2764). Run `npm run ledger-steps` to regenerate after changing");
  lines.push("LEDGER_STEPS. `npm run ledger-steps:check` fails CI if this file has drifted from a");
  lines.push("fresh regeneration (test/every-ledger-step-has-a-meaning.test.ts).");
  lines.push("-->");
  lines.push("");
  lines.push("# Ledger step registry");
  lines.push("");
  lines.push(
    "Every ledger step this repo has DECODED, rendered from the same `LEDGER_STEPS` registry " +
      "`meaningOfStep` reads (W1-T2764) -- this file cannot name a meaning the registry doesn't " +
      "have, or drift out of sync with what `rmd ledger-grep` actually prints beside a matched " +
      "row. A step's own literal is NEVER renamed here or anywhere else (DECISIONS.md, " +
      "2026-08-15: ledger step names are query keys). A step this page does not list is not " +
      "undecoded FOREVER -- it is exempted, with a written reason, in " +
      "`scripts/ledger-steps-baseline.json` until someone reads its writer closely enough to add " +
      "a row here.",
  );
  lines.push("");
  for (const family of families) {
    lines.push(`## \`${family}\``);
    lines.push("");
    for (const row of byFamily.get(family)) {
      lines.push(`### \`${row.step}\``);
      lines.push("");
      lines.push(row.meaning);
      lines.push("");
      lines.push(`- **writer(s):** ${row.writer.map((w) => `\`${w}\``).join(", ")}`);
      lines.push(`- **outcomes:** ${row.outcomes.map((o) => `\`${o}\``).join(", ")}`);
      lines.push("");
    }
  }
  // Trim the trailing blank line the loop above leaves, then end with exactly one newline.
  while (lines.length > 0 && lines[lines.length - 1] === "") lines.pop();
  return lines.join("\n") + "\n";
}

function main(argv) {
  const { values } = parseArgs({
    args: argv,
    options: {
      out: { type: "string", default: DEFAULT_OUT },
      check: { type: "boolean", default: false },
    },
  });

  const fresh = renderLedgerStepsPage(LEDGER_STEPS);

  if (values.check) {
    let committed;
    try {
      committed = readFileSync(values.out, "utf8");
    } catch {
      console.error(
        `generate-ledger-steps: ${values.out} does not exist -- run 'npm run ledger-steps' to generate it.`,
      );
      process.exitCode = 1;
      return;
    }
    if (committed !== fresh) {
      console.error(
        `generate-ledger-steps: ${values.out} is STALE -- it does not match a fresh regeneration ` +
          `from src/lib/ledger-steps.ts's LEDGER_STEPS registry.\n` +
          `Run 'npm run ledger-steps' and commit the result.`,
      );
      process.exitCode = 1;
      return;
    }
    console.log(`generate-ledger-steps: OK -- ${values.out} matches the current LEDGER_STEPS registry.`);
    process.exitCode = 0;
    return;
  }

  writeFileSync(values.out, fresh);
  console.log(`generate-ledger-steps: wrote ${values.out} (${LEDGER_STEPS.length} step(s)).`);
  process.exitCode = 0;
}

// Only run when executed directly (`tsx scripts/generate-ledger-steps.mjs ...`), never on import.
if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  main(process.argv.slice(2));
}
