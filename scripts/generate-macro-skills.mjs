#!/usr/bin/env node
// scripts/generate-macro-skills.mjs — W1-T2763.
//
// THE OPERATOR'S SHORTHAND, SUBSTITUTED RATHER THAN GUESSED. The operator types macros like
// `tddr` and `grfp` into sessions and the model infers what they mean each time. Claude Code
// substitutes a skill's body VERBATIM when the operator types `/name`, and
// `disable-model-invocation: true` means only the operator can invoke it — so one tracked table
// (settings/macros.yaml) plus this generator turns a guess into a substitution.
//
// SAME SHAPE AS docs/cli-reference.md, DELIBERATELY. That file is generated from `COMMANDS` and
// byte-compared by `cli-reference:check`; a macro's expansion is a standing instruction that will
// be edited, and two hand-kept copies drift. The generated output is CONTENT-ONLY — no timestamp,
// no invocation-environment data — which is what makes `--check` a meaningful staleness gate
// rather than a permanent false positive.
//
// Usage:
//   npm run macro-skills          # regenerate .claude/skills/<name>/SKILL.md for every row
//   npm run macro-skills:check    # exit 1 if any committed file is stale, NAMING the macro
//                                 # (driven by test/operator-macros-are-generated.test.ts, so it
//                                 #  runs inside `npm test` and therefore inside CI's `ci` job)
//
// THREE REFUSALS, IN CODE RATHER THAN IN PROSE (design (iii)):
//   - a row naming a CLAUDE.md headline that does not exist is refused, QUOTING the headline, so a
//     renamed rule is a red check instead of a silently orphaned macro;
//   - a row with no expansion is refused — an empty substitution is worse than the guess it
//     replaces, because it looks deliberate;
//   - a macro may not share a name with an `rmd` verb: `/deploy` meaning one thing in a session
//     and another at the shell is exactly the ambiguity this table exists to remove.

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import { parse } from "yaml";

export const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const MACRO_TABLE_PATH = join(REPO_ROOT, "settings", "macros.yaml");
export const SKILLS_DIR = join(REPO_ROOT, ".claude", "skills");
export const CLAUDE_MD_PATH = join(REPO_ROOT, "CLAUDE.md");

/** Thrown for every refusal below, so a caller can tell a refusal from a crash. */
export class MacroSkillError extends Error {}

/** CLAUDE.md's own `##` headlines — the set a row's `headlines` must be drawn from. Parsed from
 *  the file rather than listed here, so the check tracks the document instead of a copy of it. */
export function claudeMdHeadlines(text) {
  return [...text.matchAll(/^##\s+(.+?)\s*$/gm)].map((m) => m[1]);
}

/**
 * The frontmatter + body one macro row renders to. CONTENT-ONLY by construction: every field comes
 * from the row or from CLAUDE.md, and nothing here reads a clock, an environment or a path.
 *
 * `$ARGUMENTS` is appended last when `args` is set — Claude Code inserts it as literal text, so it
 * belongs after the instruction rather than inside it.
 */
export function renderMacroSkill(macro) {
  const lines = [
    "---",
    `name: ${macro.name}`,
    `description: ${macro.summary}`,
    "disable-model-invocation: true",
    "---",
    "",
    "<!-- GENERATED by scripts/generate-macro-skills.mjs from settings/macros.yaml — do not edit.",
    `     Edit the \`${macro.name}\` row there and run \`npm run macro-skills\`. -->`,
    "",
    macro.expansion.trimEnd(),
    "",
  ];
  if (macro.headlines?.length) {
    lines.push("Rules this invokes (CLAUDE.md):", "");
    for (const h of macro.headlines) lines.push(`- ${h}`);
    lines.push("");
  }
  if (macro.args) lines.push("$ARGUMENTS", "");
  return lines.join("\n");
}

/** Every `rmd` verb name, read from the CLI's own usage block — never a second hand-kept list. */
export function rmdVerbNames(usageText) {
  return [...usageText.matchAll(/^\s{2}rmd ([a-z][a-z-]*)/gm)].map((m) => m[1]);
}

/**
 * Validate one row against the three refusals, then return it. Every message NAMES the offending
 * value, because a refusal a reader cannot act on costs a whole re-derivation.
 */
export function validateMacro(macro, headlines, verbNames) {
  if (!macro?.name) throw new MacroSkillError("a macro row has no `name`");
  if (typeof macro.expansion !== "string" || macro.expansion.trim() === "") {
    throw new MacroSkillError(
      `macro \`${macro.name}\` has no \`expansion\` — an empty substitution is worse than the ` +
        "guess it replaces, because it looks deliberate",
    );
  }
  if (typeof macro.summary !== "string" || macro.summary.trim() === "") {
    throw new MacroSkillError(`macro \`${macro.name}\` has no \`summary\` — the skill's description line`);
  }
  if (verbNames.includes(macro.name)) {
    throw new MacroSkillError(
      `macro \`${macro.name}\` shares its name with the \`rmd ${macro.name}\` verb — one name meaning ` +
        "one thing in a session and another at the shell is the ambiguity this table exists to remove",
    );
  }
  for (const headline of macro.headlines ?? []) {
    if (!headlines.includes(headline)) {
      throw new MacroSkillError(
        `macro \`${macro.name}\` names CLAUDE.md headline "${headline}", which does not exist. ` +
          "A renamed rule must be a red check, never a silently orphaned macro. Known headlines: " +
          headlines.map((h) => `"${h}"`).join(", "),
      );
    }
  }
  return macro;
}

/** Read the table and render every row — the one function both the write and the check drive. */
export function renderAllMacroSkills(deps = {}) {
  const read = deps.readFile ?? ((p) => readFileSync(p, "utf8"));
  const table = parse(read(deps.tablePath ?? MACRO_TABLE_PATH));
  const macros = table?.macros ?? [];
  if (!Array.isArray(macros) || macros.length === 0) {
    throw new MacroSkillError("settings/macros.yaml declares no `macros:` rows");
  }
  const headlines = claudeMdHeadlines(read(deps.claudeMdPath ?? CLAUDE_MD_PATH));
  const verbNames = deps.verbNames ?? rmdVerbNames(read(join(REPO_ROOT, "docs", "cli-reference.md")));
  const seen = new Set();
  const rendered = [];
  for (const macro of macros) {
    validateMacro(macro, headlines, verbNames);
    if (seen.has(macro.name)) throw new MacroSkillError(`macro \`${macro.name}\` is declared twice`);
    seen.add(macro.name);
    rendered.push({ name: macro.name, relPath: `.claude/skills/${macro.name}/SKILL.md`, text: renderMacroSkill(macro) });
  }
  return rendered;
}

/** Skill directories on disk that no row accounts for — a macro deleted from the table must not
 *  leave its skill behind, still invocable and no longer described anywhere. */
export function orphanedSkillNames(rendered, skillsDir = SKILLS_DIR) {
  if (!existsSync(skillsDir)) return [];
  const declared = new Set(rendered.map((r) => r.name));
  return readdirSync(skillsDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !declared.has(e.name))
    .map((e) => e.name)
    .sort();
}

export function main(argv, deps = {}) {
  const { values } = parseArgs({ args: argv, options: { check: { type: "boolean" } } });
  const log = deps.log ?? console.log;
  const err = deps.error ?? console.error;
  const root = deps.repoRoot ?? REPO_ROOT;

  let rendered;
  try {
    rendered = renderAllMacroSkills(deps);
  } catch (e) {
    err(e instanceof Error ? e.message : String(e));
    return 1;
  }

  const orphans = orphanedSkillNames(rendered, deps.skillsDir ?? join(root, ".claude", "skills"));
  if (values.check) {
    const stale = [];
    for (const r of rendered) {
      const path = join(root, r.relPath);
      const onDisk = existsSync(path) ? readFileSync(path, "utf8") : null;
      if (onDisk !== r.text) stale.push(r.name);
    }
    if (stale.length || orphans.length) {
      if (stale.length) {
        err(
          `macro-skills:check: STALE — ${stale.length} generated skill(s) do not match settings/macros.yaml: ` +
            `${stale.map((n) => `\`${n}\``).join(", ")}. Edit the table, not the skill, then run \`npm run macro-skills\`.`,
        );
      }
      if (orphans.length) {
        err(
          `macro-skills:check: ORPHANED — ${orphans.map((n) => `\`${n}\``).join(", ")} exist under ` +
            ".claude/skills/ with no row in settings/macros.yaml. A deleted macro must not leave an " +
            "invocable skill behind.",
        );
      }
      return 1;
    }
    log(`macro-skills:check: OK — ${rendered.length} generated skill(s) match settings/macros.yaml.`);
    return 0;
  }

  for (const r of rendered) {
    const path = join(root, r.relPath);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, r.text);
  }
  log(`macro-skills: wrote ${rendered.length} skill(s) — ${rendered.map((r) => r.name).join(", ")}.`);
  if (orphans.length) {
    err(`macro-skills: ORPHANED skill dir(s) left in place: ${orphans.join(", ")} — remove them by hand.`);
    return 1;
  }
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  process.exitCode = main(process.argv.slice(2));
}
