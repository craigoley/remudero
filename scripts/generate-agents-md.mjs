#!/usr/bin/env node
// scripts/generate-agents-md.mjs
//
// AGENTS.md generator + drift gate (W1-T3267).
//
// CLAUDE.md remains the maintained source of repository workflow doctrine. This script renders the
// smaller Codex-facing project doc from that source's bolded rule headlines, using the same parser
// W1-T2508 already shipped in src/lib/learnings.ts. The output is content-only (no timestamp), so
// --check is a real byte-for-byte drift gate.
//
// Usage:
//   npm run agents-md
//   npm run agents-md:check

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { isMainModule } from "./lib/argv.mjs";
import { parseRuleHeadlines, renderHeadlineOnlyIndex } from "../src/lib/learnings.ts";

export const DEFAULT_SOURCE = "CLAUDE.md";
export const DEFAULT_OUT = "AGENTS.md";
export const MAX_AGENT_INDEX_TO_SOURCE_RATIO = 0.7;

export function renderAgentsMd(sourceText) {
  const rules = parseRuleHeadlines(sourceText);
  const lines = [];
  lines.push("<!--");
  lines.push("AUTO-GENERATED -- DO NOT EDIT BY HAND.");
  lines.push("Generated by scripts/generate-agents-md.mjs from CLAUDE.md's bolded rule headlines.");
  lines.push("Run `npm run agents-md` after changing CLAUDE.md. `npm run agents-md:check`");
  lines.push("fails when this file drifts from a fresh regeneration.");
  lines.push("-->");
  lines.push("");
  lines.push("# remudero worker rule index");
  lines.push("");
  lines.push("This file is the compact project doc for dispatched Codex workers.");
  lines.push("CLAUDE.md remains the maintained source; open it in this checkout when a headline's body or doctrine pointer is needed.");
  lines.push("");
  lines.push("## Rule Headlines");
  lines.push("");
  lines.push(renderHeadlineOnlyIndex(rules));
  lines.push("");
  return lines.join("\n");
}

export function renderedSizeVerdict(rendered, sourceText, maxRatio = MAX_AGENT_INDEX_TO_SOURCE_RATIO) {
  const renderedBytes = Buffer.byteLength(rendered, "utf8");
  const sourceBytes = Buffer.byteLength(sourceText, "utf8");
  const limitBytes = Math.floor(sourceBytes * maxRatio);
  return {
    ok: renderedBytes <= limitBytes,
    renderedBytes,
    sourceBytes,
    limitBytes,
    maxRatio,
  };
}

function headlineList(markdown) {
  return parseRuleHeadlines(markdown).map((rule) => rule.headline);
}

export function driftedAgentHeadlines(committed, fresh) {
  const committedHeadlines = headlineList(committed);
  const freshHeadlines = headlineList(fresh);
  const committedSet = new Set(committedHeadlines);
  const freshSet = new Set(freshHeadlines);
  return {
    missing: freshHeadlines.filter((headline) => !committedSet.has(headline)),
    unexpected: committedHeadlines.filter((headline) => !freshSet.has(headline)),
  };
}

export function main(argv) {
  const { values } = parseArgs({
    args: argv,
    options: {
      source: { type: "string", default: DEFAULT_SOURCE },
      out: { type: "string", default: DEFAULT_OUT },
      check: { type: "boolean", default: false },
    },
  });

  let sourceText;
  try {
    sourceText = readFileSync(values.source, "utf8");
  } catch (err) {
    console.error(`generate-agents-md: ${values.source} is unreadable: ${err.message}`);
    process.exitCode = 1;
    return;
  }

  let fresh;
  try {
    fresh = renderAgentsMd(sourceText);
  } catch (err) {
    console.error(`generate-agents-md: ${values.source} cannot be rendered: ${err.message}`);
    process.exitCode = 1;
    return;
  }

  const size = renderedSizeVerdict(fresh, sourceText);
  if (!size.ok) {
    console.error(
      `generate-agents-md: ${values.out} is not materially smaller than ${values.source}: ` +
        `${size.renderedBytes} bytes > ${size.limitBytes} bytes (${size.maxRatio} of ` +
        `${size.sourceBytes}).`,
    );
    process.exitCode = 1;
    return;
  }

  if (values.check) {
    if (!existsSync(values.out)) {
      console.error(`generate-agents-md: ${values.out} does not exist -- run 'npm run agents-md' to generate it.`);
      process.exitCode = 1;
      return;
    }
    const committed = readFileSync(values.out, "utf8");
    if (committed !== fresh) {
      const drift = driftedAgentHeadlines(committed, fresh);
      const missing = drift.missing.length > 0 ? ` Missing headline(s): ${drift.missing.join("; ")}.` : "";
      const unexpected = drift.unexpected.length > 0 ? ` Unexpected headline(s): ${drift.unexpected.join("; ")}.` : "";
      console.error(
        `generate-agents-md: ${values.out} is STALE -- it does not match a fresh regeneration ` +
          `from ${values.source}.${missing}${unexpected}\nRun 'npm run agents-md' and commit the result.`,
      );
      process.exitCode = 1;
      return;
    }
    console.log(
      `generate-agents-md: OK -- ${values.out} matches ${values.source} ` +
        `(${size.renderedBytes}/${size.sourceBytes} bytes).`,
    );
    process.exitCode = 0;
    return;
  }

  writeFileSync(values.out, fresh);
  console.log(`generate-agents-md: wrote ${values.out} (${size.renderedBytes}/${size.sourceBytes} bytes).`);
  process.exitCode = 0;
}

if (isMainModule(import.meta.url)) {
  main(process.argv.slice(2));
}
